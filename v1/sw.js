function ranged(res, req) {
  var range = req.headers.get('range');
  if (!range) return res;
  return res.blob().then(function (b) {
    var m = /bytes=(\d*)-(\d*)/.exec(range) || [], size = b.size, s, e;
    if (m[1] === '' || m[1] == null) { s = Math.max(0, size - (+m[2] || 0)); e = size - 1; }
    else { s = +m[1]; e = m[2] ? Math.min(+m[2], size - 1) : size - 1; }
    if (s >= size) return new Response(null, { status: 416, headers: { 'Content-Range': 'bytes */' + size } });
    return new Response(b.slice(s, e + 1), { status: 206, headers: { 'Content-Type': 'video/mp4', 'Content-Range': 'bytes ' + s + '-' + e + '/' + size, 'Content-Length': String(e - s + 1), 'Accept-Ranges': 'bytes' } });
  });
}
